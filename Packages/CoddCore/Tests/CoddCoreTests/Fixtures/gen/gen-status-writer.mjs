#!/usr/bin/env node
// Regenerates ../hooks/status-writer.golden.json.
//
// It EXECUTES the original, unmodified CODD web hook script (configs/hooks/status-writer.js) once per
// event, exactly as Claude Code would: payload on stdin, CODD_TERMINAL_ID / STATUS_DIR_PATH /
// CLAUDE_CONFIG_DIR in the environment. Side effects are confined to a fresh temp directory (HOME is
// pointed there too). `fake-date.mjs` is preloaded so `new Date()` is deterministic per step.
// After each event the hook file is read back; "written" is detected by inode change (the script
// writes via rename, and skips the write when applyEvent returns null).
//
// Usage: node gen-status-writer.mjs --web-repo <path> [--out <file>]
//   the CODD web repo (read-only) comes from --web-repo or $CODD_WEB_REPO; there is no default
import { spawnSync, execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync, readFileSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { scenarios, TERMINAL_ID, START } from './status-writer-scenarios.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const argValue = (flag, fallback) => {
  const i = args.indexOf(flag);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const webRepoArg = argValue('--web-repo', process.env.CODD_WEB_REPO);
if (!webRepoArg) {
  console.error('gen-status-writer.mjs: pass --web-repo <path to the CODD web repo> or set CODD_WEB_REPO');
  process.exit(2);
}
const webRepo = resolve(webRepoArg);
const outFile = resolve(argValue('--out', join(here, '..', 'hooks', 'status-writer.golden.json')));
const writer = join(webRepo, 'configs/hooks/status-writer.js');
const fakeDate = pathToFileURL(join(here, 'fake-date.mjs')).href;
const CONFIG_DIR = '/synthetic/.claude';

function gitCommit(repo) {
  try { return execFileSync('git', ['-C', repo, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { return null; }
}

function inode(file) {
  try { return statSync(file).ino; } catch { return null; }
}

function runScenario(sc) {
  const dir = mkdtempSync(join(tmpdir(), 'codd-golden-'));
  try {
    const hookFile = join(dir, 'status', 'term', `${TERMINAL_ID}.hook.json`);
    if (sc.seed !== undefined) {
      mkdirSync(dirname(hookFile), { recursive: true });
      writeFileSync(hookFile, sc.seed);
    }
    let t = Date.parse(START);
    const steps = [];
    for (const s of sc.steps) {
      t += s.dt;
      const now = new Date(t).toISOString();
      const stdin = s.payload !== undefined ? JSON.stringify(s.payload) : s.stdin;
      const before = inode(hookFile);
      const res = spawnSync(process.execPath, ['--import', fakeDate, writer], {
        input: stdin,
        env: {
          PATH: process.env.PATH,
          HOME: dir,
          CODD_TERMINAL_ID: TERMINAL_ID,
          STATUS_DIR_PATH: join(dir, 'status'),
          CLAUDE_CONFIG_DIR: CONFIG_DIR,
          CODD_FAKE_NOW: now,
        },
        encoding: 'utf8',
      });
      if (res.status !== 0) throw new Error(`${sc.name}: writer exited ${res.status}: ${res.stderr}`);
      const after = inode(hookFile);
      const written = after !== null && after !== before;
      const state = existsSync(hookFile) ? JSON.parse(readFileSync(hookFile, 'utf8')) : null;
      const out = { now };
      if (s.payload !== undefined) out.payload = s.payload; else out.stdin = s.stdin;
      out.written = written;
      out.state = written ? state : null;
      steps.push(out);
    }
    return { name: sc.name, seed: sc.seed ?? null, steps };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const source = readFileSync(writer);
const golden = {
  comment: 'GENERATED by gen/gen-status-writer.mjs from the original status-writer.js. Do not edit by hand.',
  source: {
    file: 'configs/hooks/status-writer.js',
    commit: gitCommit(webRepo),
    sha256: createHash('sha256').update(source).digest('hex'),
  },
  node: process.version,
  terminalId: TERMINAL_ID,
  configDir: CONFIG_DIR,
  scenarios: scenarios.map(runScenario),
};

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, JSON.stringify(golden, null, 2) + '\n');
const total = golden.scenarios.reduce((n, s) => n + s.steps.length, 0);
console.log(`wrote ${outFile}: ${golden.scenarios.length} scenarios, ${total} events (source ${golden.source.commit} ${golden.source.sha256.slice(0, 12)})`);
