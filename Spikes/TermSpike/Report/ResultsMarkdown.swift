import Foundation
import TermSpikeKit

/// Renders `RESULTS.md` from the probe and bench JSON.
enum ResultsMarkdown {
    static func render(probe: ProbeReport?, bench: BenchReport?) -> String {
        var out: [String] = []
        out.append("# TermSpike results: libghostty vs SwiftTerm")
        out.append("")
        out.append("Generated by `TermSpike --probe` and `TermSpike --bench`; rerun them instead of editing this file.")
        out.append("自動產生的量測結果；要更新請重新執行 `--probe` / `--bench`，不要手動編輯。")
        out.append("")
        out.append("## ENVIRONMENT")
        out.append("")
        let machine = bench?.machine ?? probe?.machine
        if let machine {
            out.append("- Machine: \(machine.model), \(machine.cpu), \(machine.memoryGiB) GiB, \(machine.os)")
            if let load = bench?.machine.loadAverage {
                out.append("- Load average at bench start (1 / 5 / 15 min): \(load). Other processes were running; latency tails are load-sensitive.")
            }
        }
        out.append("- Engines: \(BuildInfo.ghosttyVersion); \(BuildInfo.swiftTermVersion)")
        if let probe { out.append("- Probe run: \(probe.generatedAt), \(probe.build) build") }
        if let bench { out.append("- Bench run: \(bench.generatedAt), \(bench.build) build\(bench.quick ? " (quick)" : "")") }
        out.append("- Font: JetBrains Mono 13 pt, PingFang TC fallback; theme bg #000000, fg #e8e6d8, cursor #ffb84a")
        out.append("")

        if let probe {
            out.append(contentsOf: probeSection(probe))
        } else {
            out.append("## 1. STARTUP PROBES")
            out.append("")
            out.append("_not run yet: `TermSpike --probe`_")
            out.append("")
        }
        if let bench {
            out.append(contentsOf: benchSection(bench))
        } else {
            out.append("## 3. THROUGHPUT / MEMORY / LATENCY")
            out.append("")
            out.append("_not run yet: `TermSpike --bench`_")
            out.append("")
        }
        out.append(contentsOf: methodology)
        return out.joined(separator: "\n") + "\n"
    }

    // MARK: - Probe

    private static func probeSection(_ report: ProbeReport) -> [String] {
        var out: [String] = []
        out.append("## 1. STARTUP PROBES")
        out.append("")
        out.append("Claude Code 2.1.300's startup queries written into each engine as program output, in one burst with DA1 last (Claude itself sends two bursts, each closed by DA1). Cell = what the engine wrote back; a reply counts only if Claude's own matcher would accept it (OSC 7501 data must start with `?`, the graphics reply must carry id 31).")
        out.append("")
        let engines = report.engines
        let header = ["PROBE", "EXPECTED"] + engines.map(\.engine)
        var rows: [[String]] = []
        for (index, probe) in ClaudeProbes.all.enumerated() {
            var row = [probe.label, "`\(probe.expected)`"]
            for engine in engines {
                guard index < engine.answers.count else {
                    row.append("?")
                    continue
                }
                let answer = engine.answers[index]
                row.append(answer.answered ? "`\(answer.raw)` (\(answer.meaning))" : "**no reply**")
            }
            rows.append(row)
        }
        out.append(BenchTable.markdown(header, rows))
        out.append("")
        out.append(contentsOf: claudeSection(engines))
        for engine in engines {
            var facts = ["grid \(engine.grid)"]
            if let scale = engine.backingScale { facts.append(String(format: "backing scale %.0fx (CSI 16 t is in device pixels at this scale)", scale)) }
            if let afterExit = engine.inputAfterExit {
                let text = afterExit.map { "\($0.key) → `\($0.bytes)`" }.joined(separator: ", ")
                facts.append("keys after the host reported the child's exit: " + (afterExit.allSatisfy(\.ok) ? "still sent (\(text))" : "**not all sent** (\(text))"))
            }
            if let first = engine.firstReplyMs { facts.append(String(format: "first reply after %.2f ms", first)) }
            if !engine.unclaimed.isEmpty { facts.append("other output: `\(engine.unclaimed.joined(separator: " "))`") }
            facts.append("replay (reattach): \(engine.replay.summary). \(engine.replay.note)")
            facts.append(contentsOf: engine.notes)
            out.append("- **\(engine.engine)**: " + facts.joined(separator: "; "))
        }
        out.append("")

        out.append("## 2. KEY ENCODINGS")
        out.append("")
        out.append("Synthetic NSEvents through `NSApp.sendEvent` after each keyboard setup (reset: RIS, `CSI < 10 u`, `CSI > 4 ; 0 m`). ok = an encoding Claude's input decoder treats as intended (Shift+Enter: `\\e[13;2u` or `\\e[27;2;13~`). Claude pushes both `CSI > 1 u` and `CSI > 4 ; 2 m`, so the `claude` tables are what Claude sees; the others show what zsh / vim / other TUIs get.")
        out.append("")
        out.append("Each matrix runs under an ASCII layout first, then again (legacy and Claude's mode) with the enabled CJK input method selected, because both engines take the kitty key code from the active layout (`NSEvent.characters(byApplyingModifiers: [])`). Synthetic events bypass the input method's composition, so the second pass shows layout effects only; composition itself is in MANUAL-TEST.md.")
        out.append("")
        var seen: [String] = []
        let modeKeys = engines.flatMap(\.keyModes).map { Self.modeKey($0) }.filter { key in
            guard !seen.contains(key) else { return false }
            seen.append(key)
            return true
        }
        for key in modeKeys {
            let perEngine = engines.map { engine in engine.keyModes.first { Self.modeKey($0) == key } }
            guard let sample = perEngine.compactMap({ $0 }).first else { continue }
            var flags: [String] = []
            for (engine, mode) in zip(engines, perEngine) {
                let reply = mode?.kittyFlagsReply ?? ""
                flags.append("\(engine.engine) `CSI ? u` → `\(reply.isEmpty ? "no reply" : reply)`")
            }
            out.append("**\(sample.mode)** · input source `\(sample.inputSource ?? "not recorded")` · " + flags.joined(separator: " · "))
            out.append("")
            let keyHeader = ["KEY"] + engines.map(\.engine)
            var keyRows: [[String]] = []
            for (keyIndex, synthetic) in SyntheticKey.probeSet.enumerated() {
                var row = [synthetic.name]
                for mode in perEngine {
                    guard let mode, keyIndex < mode.keys.count else {
                        row.append("?")
                        continue
                    }
                    let result = mode.keys[keyIndex]
                    let latency = result.latencyMs.map { String(format: " · %.3f ms", $0) } ?? ""
                    row.append("\(result.ok ? "ok" : "**BAD**") `\(result.bytes)`\(latency)")
                }
                keyRows.append(row)
            }
            out.append(BenchTable.markdown(keyHeader, keyRows))
            out.append("")
        }
        return out
    }

    /// What Claude 2.1.300 would turn on with each engine's replies.
    private static func claudeSection(_ engines: [EngineProbeResult]) -> [String] {
        guard engines.contains(where: { $0.claude != nil }) else { return [] }
        var out: [String] = []
        out.append("**What Claude Code 2.1.300 enables from these replies** (rules from its bundle: two probe bursts, the second only after an XTVERSION answer; inline images only for XTVERSION `kitty` / `ghostty`; `TERM_PROGRAM` unset):")
        out.append("")
        let names = engines.compactMap(\.claude).first?.map(\.capability) ?? []
        var rows: [[String]] = []
        for (index, name) in names.enumerated() {
            var row = [name]
            for engine in engines {
                guard let verdict = engine.claude?[safe: index] else {
                    row.append("?")
                    continue
                }
                row.append("\(verdict.enabled ? "yes" : "**no**") (\(verdict.reason))")
            }
            rows.append(row)
        }
        out.append(BenchTable.markdown(["CAPABILITY"] + engines.map(\.engine), rows))
        out.append("")
        out.append("Gated on the environment, not on replies (same bundle):")
        out.append("")
        out.append(contentsOf: ClaudeCapabilities.environmentGates.map { "- \($0)" })
        out.append("")
        return out
    }

    /// Identifies a key-mode table across engines.
    private static func modeKey(_ mode: KeyModeResult) -> String {
        "\(mode.mode)|\(mode.inputSource ?? "")"
    }

    // MARK: - Bench

    private static func benchSection(_ report: BenchReport) -> [String] {
        let rows = BenchTable.rows(report)
        var out: [String] = []
        let bytes = report.results.compactMap(\.throughput).first?.bytes ?? 0
        out.append("## 3. THROUGHPUT")
        out.append("")
        let offScreen = report.results.filter { result in
            (result.warnings ?? []).contains { $0.contains("not on screen") }
        }.count
        if offScreen > 0 {
            out.append("> **\(offScreen) visible measurements ran with the window off screen** (display asleep, screen locked or window covered). AppKit then pauses SwiftTerm's display link while Ghostty keeps drawing, so visible-mode MiB/s and every streaming / peak footprint below do not compare the engines like for like. Rerun `--bench` with the screen unlocked; hidden, headless, idle and key-latency rows are unaffected.")
            out.append("")
        }
        out.append("\(bytes >> 20) MiB generated ANSI-heavy stream (SGR 256/truecolor, CJK, box drawing, alt-screen frames in mode 2026, OSC 0/8), fed from one background thread in \(FeedLoop.chunkBytes >> 10) KiB chunks, timed until fully parsed. Fresh engine per run after a 1 MiB warm-up; 1000×640 pt window on screen. STREAM `realistic` has an OSC 0 title in 0.1% of segments (Claude retitles every 960 ms); `title-heavy` in 10%, a stress case for engines that hop titles to the main thread.")
        out.append("")
        out.append(BenchTable.markdown(BenchTable.throughputHeader, rows.throughput))
        out.append("")
        out.append("## 4. MEMORY")
        out.append("")
        out.append("One worker process per row. Baseline = app with an empty on-screen window. Then N instances, 1 visible and N-1 hidden, each on a live `/bin/zsh -f` PTY and fed \(((report.results.compactMap(\.memory).first?.historyBytesPerInstance) ?? 0) >> 10) KiB of the stream as history. fp = `phys_footprint` (includes IOSurface/GPU memory), MiB.")
        out.append("")
        out.append(BenchTable.markdown(BenchTable.memoryHeader, rows.memory))
        out.append("")
        out.append(BenchTable.markdown(BenchTable.marginalHeader, rows.marginal))
        out.append("")
        out.append("Budget check (docs/ARCHITECTURE.md: total with 15 sessions < 300 MB; idle app CPU < 0.5 % with the window visible). IDLE CPU = 3 s with nothing fed. STREAMING = the visible instance is fed 16 KiB every 8 ms for 3 s (every frame has damage) while the other 14 stay hidden; PEAK fp sampled every 25 ms. The app process only: holders and children are separate processes.")
        out.append("")
        out.append(BenchTable.markdown(BenchTable.budgetHeader, rows.budget))
        out.append("")
        out.append("## 5. KEY LATENCY (HOST PATH)")
        out.append("")
        out.append("Synthetic `a` keyDowns delivered with `NSApp.sendEvent` every 12 ms into a PTY running `/bin/cat`; three rounds per engine in separate, interleaved processes. keyDown→ptyWrite: dispatch → engine encode → PTY queue → `write(2)` returned (os_signpost `keyDown→ptyWrite`). keyDown→echo fed: until the tty echo was read and handed to the engine. Not keystroke-to-glyph (needs Typometer / Instruments, see MANUAL-TEST.md).")
        out.append("")
        out.append(BenchTable.markdown(BenchTable.latencyHeader, rows.latency))
        out.append("")
        out.append("keyDown→engine output ends when the engine hands its encoding to the host (Ghostty: on its IO thread; SwiftTerm: on the main actor); the rest of keyDown→ptyWrite is the spike's hop to the PTY queue, which both engines share.")
        out.append("")
        out.append("## 6. PTY FLOOD (256 MB `cat`)")
        out.append("")
        if rows.flood.isEmpty {
            out.append("_not in this bench run_")
        } else {
            out.append("`/bin/cat` prints the stream file \(report.results.first { $0.spec.kind == .ptyFlood }?.spec.floodCopies ?? 1)× through a real PTY (cooked tty, as in a zsh tab) into the engine, with the interactive app's flow control. Timed from spawn until the child's exit was seen and every byte was parsed. Input latency during a flood (budget < 50 ms) is measured as Ctrl+C: \(BenchWorker.interruptRounds) times, `^C` is written 400 ms into a new flood and timed until the child's exit was seen and everything read was parsed, i.e. the screen stops changing (the macOS tty drops echoes of typed characters while its output queue is full, so an echo cannot be timed). macOS hands out at most 1 KiB per PTY read, so the PTY alone tops out near 150-165 MiB/s on this machine; an engine that parses on the read thread (SwiftTerm here) adds its parse time to every read.")
            out.append("")
            out.append(BenchTable.markdown(BenchTable.floodHeader, rows.flood))
        }
        out.append("")
        if !rows.errors.isEmpty {
            out.append("**Errors:**")
            out.append("")
            out.append(contentsOf: rows.errors.map { "- \($0)" })
            out.append("")
        }
        if !rows.warnings.isEmpty {
            out.append("**Warnings** (numbers on these rows are not comparable):")
            out.append("")
            out.append(contentsOf: rows.warnings.map { "- \($0)" })
            out.append("")
        }
        return out
    }

    private static let methodology: [String] = [
        "## METHODOLOGY AND CAVEATS",
        "",
        "- Ghostty runs through libghostty-spm's host-managed backend (`InMemoryTerminalSession`, `ghostty_surface_write_buffer`); there is no headless libghostty-vt API in this package, so Ghostty is always measured with a surface in a window (\"hidden\" = `ghostty_surface_set_occlusion`).",
        "- SwiftTerm runs through `TerminalView.feedSender` (parses synchronously on the feeding thread) with the Metal renderer switched on (`setUseMetal(true)`; it is off by default in 1.99.0). \"hidden\" = view not in any window. \"headless\" = `Terminal` without a view.",
        "- Throughput is parse time with rendering running concurrently in visible mode; it is not frame time. Frame pacing needs Instruments (Metal System Trace).",
        "- Memory numbers include each engine's one-time initialisation in the first instance; the marginal row isolates the cost of one more hidden session.",
        "- Key latency uses synthetic events, so it excludes the HID/WindowServer leg. Interactive numbers (HID event → PTY write) appear in each pane header and on stdout when the app quits.",
        "- Scrollback: Ghostty `scrollback-limit = 10000000` bytes; SwiftTerm 10 000 lines.",
        "- Ghostty throughput workers run with `cursor-style-blink=false`. Memory rows say which cursor setting they used: with a blinking cursor the visible surface redraws every 600 ms, which keeps Ghostty's Metal working memory (about 225 MiB) resident; with a steady cursor it is released a few seconds after the last frame. `footprint` files it under \"Owned physical footprint (unmapped) (graphics)\" (about 226 MB in 50 regions) and it is the same with no history fed, so it is not glyph-atlas growth; an upstream Ghostty.app 1.3.1 process on this Mac held 12 MB in that category (plus about 100 MB of IOSurface), so it may be specific to libghostty-spm's Metal setup or to drawing while the display sleeps. Whether SwiftTerm's Metal renderer pulls in a similar amount while it draws can only be read from rows with ON SCREEN = yes (compare its STREAMING PEAK fp and visible throughput PEAK fp with the CoreGraphics rows); until then the Ghostty / SwiftTerm streaming-memory comparison is open.",
        "- A visible measurement is only valid when ON SCREEN = yes: with the display asleep, the screen locked or the window covered, AppKit pauses SwiftTerm's display link while Ghostty keeps drawing. Such rows are listed under Warnings.",
        "- PEAK fp = highest `phys_footprint` sampled every 25 ms during the timed runs, i.e. memory while streaming.",
        "- Replay (reattach) check: the history is Claude's probe burst, then `?1049h`, `?2004h`, `?1000h`, `?1006h`, `CSI > 1 u` and a marker line. It passes only with 0 reply bytes AND the marker in the viewport AND every mode (DECRQM) and the kitty flags (`CSI ? u`) restored AND a DA1 answer afterwards. Ghostty uses libghostty-spm's `ghostty_surface_write_buffer_replay`; SwiftTerm has no replay API, so the spike drops `TerminalView.send(source: Terminal)` while the history parses (what CODD would ship with SwiftTerm).",
        "- Hidden Ghostty surfaces are created already occluded (`setSurfaceVisible(false)` before they join the window), so they never render a first frame; a single frame pulls the Metal working set in for a few seconds.",
        "- Each worker briefly activates the app and shows a floating 1000×640 window in the top-left corner of the main screen.",
        "- 原始資料：`results/probe.json`、`results/bench.json`。",
        "",
    ]
}

private extension Array {
    subscript(safe index: Int) -> Element? {
        indices.contains(index) ? self[index] : nil
    }
}
